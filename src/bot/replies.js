/** Завести недостающие реплики проекта. Написанное владельцем не трогается. */
export function ensureSeed(projectId) {
  const ins = db.prepare(
    'INSERT OR IGNORE INTO bot_replies (project_id, key, lang, text, draft, origin) VALUES (?, ?, ?, ?, 1, ?)'
  );
  const slug = db.prepare('SELECT slug FROM projects WHERE id = ?').get(projectId)?.slug || '';
  for (const [key, langs] of Object.entries(SEED)) {
    if (KEY_PROJECTS[key] && !KEY_PROJECTS[key].includes(slug)) continue;
    for (const [lang, [origin, text]] of Object.entries(langs)) ins.run(projectId, key, lang, text, origin);
  }
}

function fromRow(r) {
  return {
    id: r.id,
    key: r.key,
    lang: r.lang,
    text: r.text,
    draft: Boolean(r.draft),
    origin: r.origin,
    updatedAt: r.updated_at,
    ...(REPLY_KEYS[r.key] || { step: '', title: r.key }),
  };
}

export function list(projectId) {
  ensureSeed(projectId);
  const order = Object.keys(REPLY_KEYS);
  return db
    .prepare('SELECT * FROM bot_replies WHERE project_id = ?')
    .all(projectId)
    .map(fromRow)
    .sort((a, b) => order.indexOf(a.key) - order.indexOf(b.key) || a.lang.localeCompare(b.lang) * -1);
}

/**
 * Текст реплики на языке клиента. Нет русской — украинская: лучше ответить
 * не тем языком, чем промолчать посреди воронки.
 */
export function text(projectId, key, lang = 'uk', vars = {}) {
  ensureSeed(projectId);
  const row =
    db.prepare('SELECT text FROM bot_replies WHERE project_id = ? AND key = ? AND lang = ?').get(projectId, key, lang) ||
    db.prepare("SELECT text FROM bot_replies WHERE project_id = ? AND key = ? AND lang = 'uk'").get(projectId, key);
  if (!row) return '';
  return String(row.text).replace(/\{age\}/g, vars.age ?? '');
}

/** Правка: сохранённый текст перестаёт быть черновиком только по явной отметке. */
export function update(id, projectId, { text: value, draft } = {}) {
  const row = db.prepare('SELECT * FROM bot_replies WHERE id = ? AND project_id = ?').get(id, projectId);
  if (!row) throw new BotError('Реплика не найдена', 404);
  const next = value === undefined ? row.text : String(value).trim();
  if (!next) throw new BotError('Пустая реплика: бот промолчит посреди разговора');
  if (next.length > LIMITS.answerMax) throw new BotError(`Реплика длиннее ${LIMITS.answerMax} символов — Direct её обрежет`);
  const nextDraft = draft === undefined ? row.draft : draft ? 1 : 0;
  db.prepare('UPDATE bot_replies SET text = ?, draft = ?, origin = ?, updated_at = ? WHERE id = ?').run(
    next,
    nextDraft,
    next === row.text ? row.origin : 'own',
    nowIso(),
    id
  );
  return fromRow(db.prepare('SELECT * FROM bot_replies WHERE id = ?').get(id));
}
