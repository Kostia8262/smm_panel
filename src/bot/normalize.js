/**
 * Приведение текста к виду, в котором «Скільки коштує?» и «сколько стоит»
 * можно сравнивать.
 *
 * Модели у бота нет (решение владельца 19.10.2026), поэтому вся его
 * понятливость — здесь и в словаре синонимов. Три шага:
 *
 *   1. normalize — выброс эмодзи, знаков и регистра;
 *   2. fold      — сведение украинских и русских букв к общей основе:
 *                  «ціни» и «цины» после этого одно и то же слово;
 *   3. stem      — огрубление: отрезаем частые окончания, чтобы «коштує»,
 *                  «коштують» и «коштувало» сошлись.
 *
 * Шаги разделены намеренно: подстрочный поиск зацепки работает по folded
 * строке, а счёт по словам — по основам.
 */

import { SYNONYM_GROUPS } from './synonyms.js';

/** Регистр, апострофы, эмодзи и знаки — вон. Остаются слова и числа. */
export function normalize(text) {
  return String(text ?? '')
    .toLowerCase()
    .replace(/ё/g, 'е') // ё → е
    .replace(/[ʼ’'`´]/g, '') // апострофы: «м'який» = «мякий»
    .replace(/[^\p{L}\p{N}]+/gu, ' ')
    .trim();
}

/**
 * Сведение близких букв двух языков.
 *
 * Украинское «і», русское «и» и «ї» дают один звук в разных алфавитах, и
 * клиенты пишут как придётся — в том числе латиницей с телефона. Без этого
 * шага «ціна» и «цина» для бота разные слова.
 */
export function fold(word) {
  return String(word)
    .replace(/[іїиы]/g, 'и') // і ї и ы → и
    .replace(/[єэ]/g, 'е') // є э → е
    .replace(/ґ/g, 'г') // ґ → г
    .replace(/[ъь]/g, '') // ъ ь → ничего
    // Удвоенная буква в одном языке и одинарная в другом: «заняття» против
    // «занятия». Без схлопывания основы расходились и запись не находилась.
    .replace(new RegExp('(\\p{L})\\1+', 'gu'), '$1');
}

/*
 * Окончания от длинных к коротким: отрезаем первое подошедшее. Список
 * намеренно короткий — это не морфология, а огрубление. «Заняття» → «занят»,
 * «занятия» → «занят», «заняттях» → «занят».
 */
const ENDINGS = [
  'ованн', 'ування', 'иями', 'ння', 'ами', 'ями', 'ого', 'ему', 'ому', 'ими',
  'ост', 'ист', 'ення', 'ання', 'ити', 'ать', 'ять', 'еть', 'уть', 'ють',
  'ие', 'ия', 'ию', 'ий', 'ая', 'яя', 'ую', 'юю', 'ое', 'ые', 'их', 'ых',
  'ах', 'ях', 'ам', 'ям', 'ом', 'ем', 'ов', 'ев', 'ей', 'ою', 'ею', 'ся',
  'сь', 'ть', 'на', 'не',
  'а', 'я', 'у', 'ю', 'е', 'о', 'и', 'й', 'в',
];

/** Минимальная длина основы: короче — слово теряет смысл («дит» от «дитина»). */
const STEM_MIN = 4;

export function stem(word) {
  const w = fold(normalize(word));
  if (w.length <= STEM_MIN) return w;
  for (const end of ENDINGS) {
    if (w.length - end.length >= STEM_MIN && w.endsWith(end)) return w.slice(0, -end.length);
  }
  return w;
}

/*
 * Служебные слова выбрасываем: без этого «а скільки у вас стоїт» совпадает с
 * любой записью, где есть «у вас».
 */
const STOPWORDS = new Set(
  [
    'и', 'а', 'но', 'або', 'или', 'та', 'и', 'в', 'во', 'на', 'з', 'с', 'со',
    'у', 'до', 'по', 'за', 'от', 'од', 'про', 'для', 'не', 'ни', 'ні', 'да',
    'так', 'что', 'що', 'чи', 'как', 'як', 'ли', 'бы', 'би', 'же', 'ж',
    'это', 'цэ', 'це', 'вот', 'там', 'тут', 'ваш', 'ваша', 'ваши', 'вашы',
    'мой', 'моя', 'мои', 'вы', 'ви', 'мы', 'ми', 'я', 'он', 'она', 'они',
    'есть', 'є', 'буду', 'будет', 'буде', 'был', 'была', 'было', 'якщо',
    // Вопросительные слова несут вопрос, но не тему: «яка погода» и «яка
    // адреса» совпадали на половину слов и давали черновик на ровном месте.
    'яка', 'який', 'яке', 'які', 'якої', 'якому', 'якась',
    'какой', 'какая', 'какое', 'какие', 'каком', 'каким',
    'хто', 'кто', 'кого', 'куди', 'куда', 'чому', 'почему', 'навіщо', 'зачем',
    'де', 'где', 'звідки', 'откуда', 'коли',
    'если', 'можно', 'можна', 'подскажите', 'підскажіть', 'скажите',
    'скажіть', 'добрый', 'добрий', 'день', 'вечер', 'вечір', 'привет',
    'привіт', 'здравствуйте', 'вітаю', 'доброго', 'пожалуйста', 'будь',
    'ласка', 'спасибо', 'дякую',
  ].map((w) => fold(w))
);

/**
 * Словарь синонимов, собранный из групп: основа слова → имя группы.
 *
 * Строится один раз при загрузке модуля. Группы задаются живыми словами
 * (src/bot/synonyms.js) и приводятся к основам теми же правилами, что и
 * текст клиента, — иначе словарь разъехался бы с подбором.
 */
const SYNONYMS = new Map();
for (const [name, words] of Object.entries(SYNONYM_GROUPS)) {
  for (const word of words) {
    // Многословные синонимы («де ви», «сколько детей») словарю не нужны: по
    // словам они не ищутся, а целой строкой их ловит зацепка записи.
    if (word.includes(' ')) continue;
    const key = stem(word);
    if (key.length >= 3) SYNONYMS.set(key, `=${name}`);
  }
}

/** Слово → его основа или имя группы синонимов. */
export function canonical(word) {
  const base = stem(word);
  return SYNONYMS.get(base) || base;
}

/**
 * Слова текста: основы без служебных, с заменой синонимов на имя группы.
 * Порядок сохраняется, повторы убираются.
 */
export function tokens(text) {
  const out = [];
  for (const raw of normalize(text).split(' ')) {
    if (!raw) continue;
    const folded = fold(raw);
    if (STOPWORDS.has(folded)) continue;
    // Числа оставляем как есть: «7 років» и «з 7 років» — это про возраст.
    const word = /^\p{N}+$/u.test(raw) ? raw : canonical(raw);
    if (word.length < 2) continue;
    if (!out.includes(word)) out.push(word);
  }
  return out;
}

/** Строка для подстрочного поиска зацепки целиком. */
export function flat(text) {
  return fold(normalize(text));
}
